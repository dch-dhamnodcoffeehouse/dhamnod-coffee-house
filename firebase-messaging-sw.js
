const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const notificationTitle = "☕ New DCH Order!";
  const notificationOptions = {
    body: payload.data?.body || "Check your live dashboard for details.",
    icon: './icon-192.png',
    badge: './icon-192.png',
    vibrate: [500, 200, 500, 200, 500],
    tag: 'dch-order-alert',
    renotify: true,
    data: { click_action: './admin.html' }
  };
  return self.registration.showNotification(notificationTitle, notificationOptions);
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windowClients) => {
      for (let i = 0; i < windowClients.length; i++) {
        let client = windowClients[i];
        if (client.url.includes('admin.html') && 'focus' in client) return client.focus();
      }
      if (clients.openWindow) return clients.openWindow('./admin.html');
    })
  );
});
